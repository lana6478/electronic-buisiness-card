#!/usr/bin/env python3
"""
Turn your photo(s) and a link into C header files for the business card.

  pip install -r tools/requirements.txt

  # your photo + a QR code to your website
  python3 tools/make_assets.py --photo me.jpg --qr https://github.com/you

  # 240x240 screen (1.54"/1.3")
  python3 tools/make_assets.py --photo me.jpg --height 240

Writes photo.h and/or qr.h into firmware/business_card/ (the sketch picks
them up automatically). Delete the .h file to go back to the placeholder.
"""
import argparse
import pathlib
import sys

from PIL import Image, ImageOps

HERE = pathlib.Path(__file__).resolve().parent
DEFAULT_OUT = HERE.parent / "firmware" / "business_card"


def rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def make_photo(path, w, h, out):
    img = Image.open(path)
    img = ImageOps.exif_transpose(img).convert("RGB")
    img = ImageOps.fit(img, (w, h), Image.LANCZOS, centering=(0.5, 0.35))
    px = [rgb565(*c) for c in img.getdata()]
    lines = ["// Generated by tools/make_assets.py - do not edit by hand", "#pragma once",
             "#include <Arduino.h>", f"// {pathlib.Path(path).name}",
             f"#define PHOTO_W {w}", f"#define PHOTO_H {h}",
             f"const uint16_t PHOTO[{w * h}] PROGMEM = {{"]
    for j in range(0, len(px), 16):
        lines.append("  " + ",".join(f"0x{v:04X}" for v in px[j:j + 16]) + ",")
    lines.append("};")
    print(f"  photo: {path} -> {w}x{h}")
    (out / "photo.h").write_text("\n".join(lines) + "\n")
    print(f"wrote {out / 'photo.h'}")


def make_qr(data, out):
    try:
        import qrcode
    except ImportError:
        sys.exit("QR needs the qrcode package:  pip install qrcode")
    qr = qrcode.QRCode(border=0, error_correction=qrcode.constants.ERROR_CORRECT_L)
    qr.add_data(data)
    qr.make(fit=True)
    m = qr.get_matrix()
    n = len(m)
    if n > 50:
        print(f"WARNING: QR is {n}x{n} modules - too dense to scan easily. "
              "Use a shorter link (e.g. a link shortener).")
    row_bytes = (n + 7) // 8
    data_bytes = []
    for row in m:
        for b in range(row_bytes):
            byte = 0
            for bit in range(8):
                x = b * 8 + bit
                if x < n and row[x]:
                    byte |= 0x80 >> bit
            data_bytes.append(byte)
    lines = ["// Generated by tools/make_assets.py - do not edit by hand", "#pragma once",
             "#include <Arduino.h>", f"// {data}", f"#define QR_SIZE {n}",
             f"const uint8_t QR_BITS[{len(data_bytes)}] PROGMEM = {{"]
    for j in range(0, len(data_bytes), 16):
        lines.append("  " + ",".join(f"0x{v:02X}" for v in data_bytes[j:j + 16]) + ",")
    lines.append("};")
    (out / "qr.h").write_text("\n".join(lines) + "\n")
    print(f"wrote {out / 'qr.h'}  ({n}x{n} modules)")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--photo", help="image file for the colour screen")
    ap.add_argument("--qr", help="link/text to show as a QR code on the OLED")
    ap.add_argument("--width", type=int, default=240)
    ap.add_argument("--height", type=int, default=280)
    ap.add_argument("--out", type=pathlib.Path, default=DEFAULT_OUT)
    a = ap.parse_args()
    if not a.photo and not a.qr:
        ap.error("give --photo and/or --qr")
    a.out.mkdir(parents=True, exist_ok=True)
    if a.photo:
        make_photo(a.photo, a.width, a.height, a.out)
    if a.qr:
        make_qr(a.qr, a.out)


if __name__ == "__main__":
    main()
